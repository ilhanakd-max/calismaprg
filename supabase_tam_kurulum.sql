-- SUPABASE POSTGRESQL SCHEMA VE VERİLERİ --

-- 1. Tabloları temizle (Varsa)
DROP TABLE IF EXISTS public.mesailer CASCADE;
DROP TABLE IF EXISTS public.gorev_tamamlayanlar CASCADE;
DROP TABLE IF EXISTS public.duyurular CASCADE;
DROP TABLE IF EXISTS public.personeller CASCADE;
DROP TABLE IF EXISTS public.birimler CASCADE;
DROP TABLE IF EXISTS public.ayarlar CASCADE;
DROP TABLE IF EXISTS public.kullanicilar CASCADE;
DROP TABLE IF EXISTS public.resmi_tatiller CASCADE;

-- 2. Tabloları Oluştur

CREATE TABLE public.ayarlar (
  id bigint generated by default as identity primary key,
  ayar_anahtar text NOT NULL,
  ayar_deger text
);

CREATE TABLE public.birimler (
  id bigint generated by default as identity primary key,
  birim_adi text NOT NULL,
  olusturulma_tarihi timestamp default now()
);

CREATE TABLE public.personeller (
  id bigint generated by default as identity primary key,
  ad_soyad text NOT NULL,
  birim_id bigint NOT NULL REFERENCES public.birimler(id) ON DELETE SET NULL,
  olusturulma_tarihi timestamp default now(),
  izin_degistirici integer DEFAULT 0,
  cikis_tarihi date DEFAULT NULL,
  dogum_tarihi date DEFAULT NULL,
  telefon text DEFAULT NULL,
  adres text DEFAULT NULL,
  email text DEFAULT NULL
);

CREATE TABLE public.mesailer (
  id bigint generated by default as identity primary key,
  personel_id bigint NOT NULL REFERENCES public.personeller(id) ON DELETE CASCADE,
  birim_id bigint DEFAULT NULL REFERENCES public.birimler(id) ON DELETE SET NULL,
  tarih date NOT NULL,
  baslangic_saati time DEFAULT NULL,
  bitis_saati time DEFAULT NULL,
  durum text DEFAULT 'Çalışıyor',
  notlar text DEFAULT NULL,
  olusturulma_tarihi timestamp default now()
);

CREATE TABLE public.duyurular (
  id bigint generated by default as identity primary key,
  baslik text NOT NULL,
  icerik text NOT NULL,
  baslangic_tarihi timestamp DEFAULT NULL,
  bitis_tarihi timestamp DEFAULT NULL,
  birim_id bigint DEFAULT 0,
  aktif integer DEFAULT 1,
  olusturan text DEFAULT NULL,
  tur text NOT NULL DEFAULT 'duyuru',
  olusturulma_tarihi timestamp default now()
);

CREATE TABLE public.gorev_tamamlayanlar (
  id bigint generated by default as identity primary key,
  gorev_id bigint NOT NULL REFERENCES public.duyurular(id) ON DELETE CASCADE,
  isim text NOT NULL,
  tamamlanma_tarihi timestamp default now()
);

CREATE TABLE public.kullanicilar (
  id bigint generated by default as identity primary key,
  kullanici_adi text NOT NULL,
  sifre text NOT NULL,
  olusturulma_tarihi timestamp default now()
);

CREATE TABLE public.resmi_tatiller (
  id bigint generated by default as identity primary key,
  gun_ay text NOT NULL,
  aciklama text NOT NULL
);

